// Regenerates src/webview/grammars.ts from shiki's own language metadata.
// Run after upgrading shiki:  node scripts/gen-grammars.mjs
import { writeFile } from 'node:fs/promises'
import { bundledLanguagesInfo } from 'shiki'

const ids = bundledLanguagesInfo.map(l => l.id).sort()
const key = id => (/^[a-z][a-z0-9]*$/.test(id) ? id : `'${id}'`)

const loaders = ids.map(id => `  ${key(id)}: () => import('shiki/langs/${id}.mjs'),`).join('\n')

// an alias is usually the file extension too (py, rs, yml, ts); ids double as extensions
const aliases = {}
for (const lang of bundledLanguagesInfo) {
  for (const name of [lang.id, ...(lang.aliases ?? [])]) {
    if (/^[a-z0-9+#._-]+$/.test(name) && !(name in aliases)) {
      aliases[name] = lang.id
    }
  }
}
const entries = Object.keys(aliases).sort().map(a => `  ${key(a)}: '${aliases[a]}',`).join('\n')

await writeFile(
  'src/webview/grammars.ts',
  `// Generated by scripts/gen-grammars.mjs from shiki's bundledLanguagesInfo. Do not edit.
import type { HighlighterCore } from 'shiki/core'

/** grammarLoaders imports one grammar on demand; vite splits each into its own chunk. */
export const grammarLoaders: Record<string, GrammarLoader> = {
${loaders}
}

/** aliasExtensions maps every shiki language id and alias to its grammar. */
export const aliasExtensions: Record<string, string> = {
${entries}
}

/** GrammarLoader imports one grammar module lazily. */
export type GrammarLoader = () => Promise<{ default: Parameters<HighlighterCore['loadLanguage']>[0] }>
`,
)
console.log(`wrote src/webview/grammars.ts: ${ids.length} grammars, ${Object.keys(aliases).length} extension aliases`)
